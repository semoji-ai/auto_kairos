def gallery_names(g):
    txt = open(os.path.join(VSRC, "gallery", f"{g}.tsx"), encoding="utf-8").read()
    body = txt.split("export const DEMOS", 1)[1] if "export const DEMOS" in txt else ""
    body = body.split("export const GALLERY_DUR", 1)[0]
    names = re.findall(r'(?:^\s*(?:\{\s*name:|AB\(\{\s*name:|D\()\s*)"([^"]+)"', body, re.M)
    return names


def gallery_ids(g):
    """데모 id — DEMOS 항목에 id: "..." 가 있으면 그것(예: demo-wipe-reveal-bubble), 없으면 group-NN.
    registry.tsx 의 ENTRIES 와 같은 규칙."""
    txt = open(os.path.join(VSRC, "gallery", f"{g}.tsx"), encoding="utf-8").read()
    body = txt.split("export const DEMOS", 1)[1] if "export const DEMOS" in txt else ""
    body = body.split("export const GALLERY_DUR", 1)[0]
    out = []
    for i, m in enumerate(re.finditer(r'(?:^\s*(?:\{\s*name:|AB\(\{\s*name:|D\()\s*)"([^"]+)"(.*)$', body, re.M)):
        x = re.search(r'\bid:\s*"([^"]+)"', m.group(2))
        out.append(x.group(1) if x else f"{g}-{i + 1:02d}")
    return out


