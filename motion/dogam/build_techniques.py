def core_preview(comp):
    for i, n in enumerate(GAL["core"]):
        head = re.split(r"\s+[—-]\s+", n, maxsplit=1)[0].strip()
        if head == comp:
            return GAL_IDS["core"][i]
    return None


# ── ref4(애플·현대·삼성·코카콜라 통합편) 분석 JSON 병합 ─────────────────────
#   analysis/ref4_*.json 을 그대로 흡수한다(분석 에이전트가 같은 스키마로 작성).
#   id 가 기존 항목과 겹치면 sources 만 합치고, 같은 파일 묶음 안 중복 id 는 접미사를 붙인다.
import glob
R4_CAT_FIX = {"HUD·포맷": "HUD·자막·포맷", "구성": "구성·엔딩"}
by_id = {e["id"]: e for e in ENTRIES}
merged_new = merged_dup = 0
for fn in sorted(glob.glob(os.path.join(ROOT, "analysis", "ref4_*.json"))):
    for r in json.load(open(fn, encoding="utf-8")):
        r = dict(r)
        r["category"] = R4_CAT_FIX.get(r.get("category"), r.get("category"))
        r.setdefault("tags", []); r.setdefault("sources", [])
        r["component"] = r.get("component"); r["file"] = r.get("file"); r["preview"] = r.get("preview")
        if r.get("status") not in STATUS:
            r["status"] = "분석만"
        rid = re.sub(r"[^a-z0-9-]", "", str(r["id"]).lower()).strip("-") or "ref4-item"
        r["id"] = rid
        if rid in by_id:
            old = by_id[rid]
            if old.get("_ref4"):          # ref4 끼리 같은 이름 → 출처만 합침
                old["sources"] += r["sources"]; merged_dup += 1; continue
            rid = r["id"] = rid + "-r4"     # 기존(ref1~3) 항목과 id 만 겹침 → 별개 항목으로
        r["_ref4"] = True
        r["tags"] = list(dict.fromkeys(list(r["tags"]) + ["ref4"]))
        ENTRIES.append(r); by_id[rid] = r; merged_new += 1
print(f"[ref4 병합] 신규 {merged_new}, 출처 합침 {merged_dup}")

# 새로 구현된 기법 반영: impl/<group>.json = {기법id: {"component": 이름, "preview": "x_…-NN", "note": ""}}
#   분석만 → 구현 으로 바꾸고, 중복으로 합친 기법은 {"mergedInto": 다른 id} 로 표시
IMPL = {}
for fn in sorted(glob.glob(os.path.join(ROOT, "impl", "*.json"))):
    IMPL.update(json.load(open(fn, encoding="utf-8")))
for tid, v in sorted(IMPL.items(), key=lambda kv: bool(kv[1].get("mergedInto"))):   # 실제 구현 먼저, 중복 연결은 나중
    e = by_id.get(tid)
    if not e and v.get("name"):
        # 신규 기법 전체 항목(impl/x_explainer.json 등): id·name·category·summary·spec·sources·component·file·preview·status·tags
        #   "option-of": 기존 기법 id → 그 기법에 추가한 옵션(변수)을 따로 보여주는 항목
        r = {k: v.get(k) for k in ("name", "category", "summary", "spec", "sources", "component", "file", "preview", "status", "tags")}
        r["id"] = tid; r["sources"] = r["sources"] or []; r["tags"] = list(r["tags"] or [])
        if r["status"] not in STATUS:
            r["status"] = "구현" if r["component"] else "분석만"
        of = v.get("option-of")
        if of:
            if of not in by_id:
                print(f"[impl] {tid}: option-of {of} 없음")
            r["optionOf"] = of
            r["tags"] = list(dict.fromkeys(r["tags"] + ["옵션→" + of]))
        ENTRIES.append(r); by_id[tid] = r
        continue
    if not e:
        print(f"[impl] 알 수 없는 id {tid}"); continue
    tgt = by_id.get(v.get("mergedInto")) if v.get("mergedInto") else None
    if v.get("mergedInto") and not tgt:
        print(f"[impl] {tid}: mergedInto {v['mergedInto']} 없음"); continue
    src = tgt if tgt else v
    e["component"], e["status"], e["file"] = src.get("component"), "구현", (tgt.get("file") if tgt else None)
    e["preview"] = src.get("preview") or e.get("preview")
    extra = (["중복→" + v["mergedInto"]] if tgt else []) + ([v["note"]] if v.get("note") else [])
    e["tags"] = list(dict.fromkeys(e["tags"] + extra))

