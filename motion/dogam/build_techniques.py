def mmss(sec):
    """초(float) → m:ss (60분 넘으면 분이 그대로 커진다: 147:16)"""
    sec = int(round(sec))
    return f"{sec // 60}:{sec % 60:02d}"


def S(ref, time, note=""):
    """time: 숫자(초) 또는 'mm:ss' 문자열"""
    t = mmss(time) if isinstance(time, (int, float)) else time
    return {"ref": ref, "video": VID[ref], "time": t, "note": note}


